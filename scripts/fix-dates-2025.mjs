async function main() {
  // Find all posts with 2026 dates
  const posts = await client.fetch(
    `*[_type == "post" && publishedAt match "2026-*"] {
      _id,
      title,
      publishedAt
    } | order(publishedAt asc)`
  );

  console.log(`📋 Encontrados ${posts.length} posts con fechas 2026\n`);

  let fixed = 0;
  let skipped = 0;

  for (const post of posts) {
    const newDate = dateMap[post.publishedAt];
    if (!newDate) {
      console.log(`⚠️  ${post.publishedAt} | ${post.title} — SIN MAPEO, se omite`);
      skipped++;
      continue;
    }

    await client.patch(post._id)
      .set({ publishedAt: newDate })
      .commit();

    console.log(`✅ ${post.publishedAt} → ${newDate} | ${post.title}`);
    fixed++;
  }

  console.log(`\n=== RESUMEN ===`);
  console.log(`${fixed} actualizados, ${skipped} omitidos (sin mapeo), ${posts.length - fixed - skipped} errores`);
}

main().catch(e => { console.error('❌ Error fatal:', e.message); process.exit(1); });
